import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { allIndiaCuratedPlaces, isInsideIndiaBounds } from './curatedPlacesMaster.js'
import { processAllPlaces } from './fetchWikidataImages.js'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

async function run() {
  console.log('🚀 Starting Nationwide India Places Seeding Pipeline...\n')
  const startTime = Date.now()

  const enrichedPlaces = await processAllPlaces(allIndiaCuratedPlaces)

  // Integrity Validation
  const shaMap = new Map()
  const urlMap = new Map()
  const stateCounts = {}
  const coordinateErrors = []

  enrichedPlaces.forEach((p) => {
    // Check bounds
    if (!isInsideIndiaBounds(p.lat, p.lng)) {
      coordinateErrors.push(`${p.name} (${p.lat}, ${p.lng}) outside India`)
    }

    // State count
    stateCounts[p.state] = (stateCounts[p.state] || 0) + 1

    // Check duplicate sha256
    const sha = p.image.sha256
    if (shaMap.has(sha)) {
      throw new Error(`CRITICAL INTEGRITY FAILURE: Duplicate SHA-256 between "${shaMap.get(sha)}" and "${p.name}"!`)
    }
    shaMap.set(sha, p.name)

    // Check duplicate URL
    const imgUrl = p.image.url
    if (urlMap.has(imgUrl)) {
      throw new Error(`CRITICAL INTEGRITY FAILURE: Duplicate Image URL between "${urlMap.get(imgUrl)}" and "${p.name}"!`)
    }
    urlMap.set(imgUrl, p.name)
  })

  if (coordinateErrors.length > 0) {
    console.warn(`[WARN] ${coordinateErrors.length} places had out-of-bounds coordinates!`, coordinateErrors)
  }

  console.log(`\n✅ Verified ${enrichedPlaces.length} places across ${Object.keys(stateCounts).length} Indian States & Union Territories.`)
  console.log('Sample State Distribution:')
  Object.entries(stateCounts).slice(0, 10).forEach(([st, count]) => {
    console.log(`  - ${st}: ${count} places`)
  })

  // Format data for frontend runtime
  const formattedForFrontend = enrichedPlaces.map((p) => {
    return {
      id: p.id,
      name: p.name,
      wikidata_id: p.wikidata_id,
      wiki_title: p.wiki_title,
      type: p.type,
      category: p.category,
      state: p.state,
      city: p.city,
      position: [p.lat, p.lng],
      location: {
        address: `${p.city}, ${p.state}, India`,
        coordinates: [p.lng, p.lat],
        state: p.state,
        city: p.city,
      },
      lat: p.lat,
      lng: p.lng,
      image: p.image.url,
      images: p.images,
      image_attribution: p.image.attribution,
      image_license: p.image.license,
      is_illustration: p.image.is_illustration || false,
      price: p.price_amount !== null ? {
        amount: p.price_amount,
        currency: 'INR',
        unit: p.price_unit || 'per person',
        source: p.price_source || null,
        last_verified_at: p.price_last_verified || null,
      } : null,
      price_display: p.price_amount !== null ? `₹${p.price_amount.toLocaleString('en-IN')}` : 'Not listed, verify locally',
      opening_hours: p.opening_hours || null,
      best_time: p.best_time || null,
      rules: p.rules || null,
      tags: p.tags || [],
      description: p.description,
      // Ratings: show real user review count only (0 initially for newly seeded places)
      rating: p.rating_count ? p.rating : null,
      rating_count: p.rating_count || 0,
      is_published: true,
      last_verified_at: new Date().toISOString(),
    }
  })

  // 1. Write `src/data/indiaPlacesData.js`
  const targetFrontendPath = path.join(__dirname, '../../src/data/indiaPlacesData.js')
  const fileContent = `// Automatically generated by Explorex Nationwide Seeding Pipeline (${new Date().toISOString()})
// Total Places: ${formattedForFrontend.length} | States & UTs: ${Object.keys(stateCounts).length}

export const indiaPlaces = ${JSON.stringify(formattedForFrontend, null, 2)};

export default indiaPlaces;
`
  fs.writeFileSync(targetFrontendPath, fileContent, 'utf-8')
  console.log(`\nWritten ${formattedForFrontend.length} places to ${targetFrontendPath}`)

  // 2. Generate Supabase SQL seed migration
  const sqlLines = [
    '-- Supabase SQL Migration: Seed Nationwide India Places',
    '-- Generated: ' + new Date().toISOString(),
    '',
  ]

  formattedForFrontend.forEach((p) => {
    const rulesJson = JSON.stringify(p.rules || []).replace(/'/g, "''")
    const tagsSql = p.tags && p.tags.length > 0 ? `ARRAY[${p.tags.map((t) => `'${t.replace(/'/g, "''")}'`).join(',')}]` : 'ARRAY[]::text[]'
    const nameSql = p.name.replace(/'/g, "''")
    const descSql = (p.description || '').replace(/'/g, "''")
    const citySql = (p.city || '').replace(/'/g, "''")
    const stateSql = (p.state || '').replace(/'/g, "''")
    const catSql = (p.category || '').replace(/'/g, "''")
    const hoursSql = p.opening_hours ? `'${p.opening_hours.replace(/'/g, "''")}'` : 'NULL'
    const bestTimeSql = p.best_time ? `'${p.best_time.replace(/'/g, "''")}'` : 'NULL'
    const priceAmountSql = p.price ? p.price.amount : 'NULL'
    const priceUnitSql = p.price ? `'${p.price.unit.replace(/'/g, "''")}'` : 'NULL'

    sqlLines.push(`
INSERT INTO public.places (
  slug, name, type, category, state, city, address, lat, lng, description, rules,
  price_amount, price_unit, opening_hours, best_time, tags, wikidata_id, is_published
) VALUES (
  '${p.id}', '${nameSql}', '${p.type}', '${catSql}', '${stateSql}', '${citySql}',
  '${p.location.address.replace(/'/g, "''")}', ${p.lat}, ${p.lng}, '${descSql}',
  '${rulesJson}'::jsonb, ${priceAmountSql}, ${priceUnitSql}, ${hoursSql}, ${bestTimeSql},
  ${tagsSql}, '${p.wikidata_id}', true
) ON CONFLICT (slug) DO UPDATE SET
  name = EXCLUDED.name,
  lat = EXCLUDED.lat,
  lng = EXCLUDED.lng,
  description = EXCLUDED.description,
  price_amount = EXCLUDED.price_amount,
  opening_hours = EXCLUDED.opening_hours;
`)

    if (p.images && p.images[0]) {
      const img = p.images[0]
      const attrSql = (img.attribution || '').replace(/'/g, "''")
      const licSql = (img.license || '').replace(/'/g, "''")
      sqlLines.push(`
INSERT INTO public.place_images (
  place_id, url, source, license, attribution, width, height, sha256, is_primary, is_verified
) SELECT
  id, '${img.url.replace(/'/g, "''")}', '${img.source}', '${licSql}', '${attrSql}',
  ${img.width || 1200}, ${img.height || 800}, '${img.sha256}', true, ${img.is_verified ? 'true' : 'false'}
FROM public.places WHERE slug = '${p.id}'
ON CONFLICT (sha256) DO NOTHING;
`)
    }
  })

  const sqlPath = path.join(__dirname, '../../supabase/migrations/20261024000004_seed_india_places.sql')
  fs.writeFileSync(sqlPath, sqlLines.join('\n'), 'utf-8')
  console.log(`Written Supabase migration to ${sqlPath}`)

  const elapsed = ((Date.now() - startTime) / 1000).toFixed(1)
  console.log(`\n🎉 Seeding pipeline completed successfully in ${elapsed}s!`)
}

run().catch((err) => {
  console.error('Fatal Seeding Error:', err)
  process.exit(1)
})
